/**
 * SOCAL SUBSURFACE — shared geodesy + vertical-scale state.
 *
 * Both the infrastructure theater and the vector overlay pack have to agree on
 * exactly one projection and exactly one elevation field, or draped polygons
 * float off the hillsides. So the transform lives here, once.
 *
 * Projection: local equirectangular about CENTER, 1 scene unit = 10 km.
 * Elevation:  synthesized gaussian-relief field (metres), NOT a DEM download.
 *             See docs/terrain-vector-overlay-deep-dive.md for why, and for
 *             the 3DEP path to replace it with real 1/3 arc-second data.
 */

import { CENTER, KM_PER_DEG_LAT, RELIEF, UNITS_PER_KM } from "./socal-subsurface-data.js";

export const COS_LAT = Math.cos((CENTER.lat * Math.PI) / 180);

/** Mutable vertical-scale state shared by every module that draws in the scene. */
export const scale = {
  vert: 6, // terrain exaggeration, linear
  depth: 14, // depth gain, logarithmic (see depthY)
};

/** lon/lat -> scene XZ. */
export function project(lon, lat) {
  const x = (lon - CENTER.lon) * KM_PER_DEG_LAT * COS_LAT * UNITS_PER_KM;
  const z = -(lat - CENTER.lat) * KM_PER_DEG_LAT * UNITS_PER_KM;
  return [x, z];
}

/** scene XZ -> lon/lat. */
export function lonLatFromXZ(x, z) {
  const lat = CENTER.lat - z / (KM_PER_DEG_LAT * UNITS_PER_KM);
  const lon = CENTER.lon + x / (KM_PER_DEG_LAT * COS_LAT * UNITS_PER_KM);
  return [lon, lat];
}

/** Metres of elevation -> scene Y (linear, exaggerated). */
export const elevY = (m) => (m / 1000) * UNITS_PER_KM * 10 * scale.vert * 0.1;

/**
 * Metres of depth (negative) -> scene Y offset, LOGARITHMIC.
 *
 * A trench-buried products line sits ~1.5 m down; a geothermal production zone
 * sits ~2,000 m down. On a 700 km wide stage a linear depth axis makes the
 * first invisible and the second a hairline. Ordering and order-of-magnitude
 * survive the log10 ramp; absolute spacing does not.
 */
export function depthY(m) {
  if (!m) return 0;
  const mag = 0.35 + 0.45 * Math.log10(1 + Math.abs(m));
  return -mag * (scale.depth / 10);
}

/* ------------------------------------------------------------- DEM hook */

/**
 * Optional real elevation grid (USGS 3DEP). When one is installed every
 * consumer of elevationAt() — terrain mesh, corridors, fire rings, radio
 * propagation, the relief map — switches to it at once, because they all go
 * through this one function.
 *
 * Shape: { lon0, lat0, lon1, lat1, nx, ny, data: Int16Array|Float32Array }
 * Row-major, north-to-south (data[0] is the north-west corner), metres.
 * Generated by scripts/fetch-3dep-dem.py; absent from the repo by default
 * because the app ships offline and a real grid is a large binary asset.
 */
let DEM = null;

export function installDem(grid) {
  if (!grid || !grid.data || !grid.nx || !grid.ny) return false;
  DEM = grid;
  return true;
}

export function demInfo() {
  if (!DEM) return null;
  return {
    nx: DEM.nx,
    ny: DEM.ny,
    bbox: { lon0: DEM.lon0, lat0: DEM.lat0, lon1: DEM.lon1, lat1: DEM.lat1 },
    source: DEM.source || "USGS 3DEP",
    resolution: DEM.resolution || "unstated",
    retrieved: DEM.retrieved || "unstated",
    cellKm: ((DEM.lon1 - DEM.lon0) / DEM.nx) * 111.32 * COS_LAT,
  };
}

/** Bilinear sample of the installed DEM, or null when outside/absent. */
function demSample(lon, lat) {
  if (!DEM) return null;
  const { lon0, lon1, lat0, lat1, nx, ny, data } = DEM;
  if (lon < lon0 || lon > lon1 || lat < lat0 || lat > lat1) return null;
  const fx = ((lon - lon0) / (lon1 - lon0)) * (nx - 1);
  const fy = ((lat1 - lat) / (lat1 - lat0)) * (ny - 1);
  const x0 = Math.floor(fx);
  const y0 = Math.floor(fy);
  const x1 = Math.min(x0 + 1, nx - 1);
  const y1 = Math.min(y0 + 1, ny - 1);
  const tx = fx - x0;
  const ty = fy - y0;
  const a = data[y0 * nx + x0];
  const b = data[y0 * nx + x1];
  const c = data[y1 * nx + x0];
  const d = data[y1 * nx + x1];
  return (a * (1 - tx) + b * tx) * (1 - ty) + (c * (1 - tx) + d * tx) * ty;
}

/** Generalized elevation field in metres from the RELIEF control features. */
export function elevationAt(lon, lat) {
  if (DEM) {
    const s = demSample(lon, lat);
    if (s !== null) return s;
  }
  let e = 120;
  for (const f of RELIEF) {
    const dx = lon - f.lon;
    const dy = lat - f.lat;
    const c = Math.cos(f.rot || 0);
    const s = Math.sin(f.rot || 0);
    const u = (dx * c + dy * s) / f.rx;
    const v = (-dx * s + dy * c) / f.ry;
    e += f.amp * Math.exp(-(u * u + v * v) * 1.5);
  }
  // Light fractal texture so ridges are not billiard-smooth.
  e += 90 * (Math.sin(lon * 21.3 + lat * 13.7) + Math.sin(lon * 9.1 - lat * 31.4)) * 0.5;
  return e;
}

/** Great-circle-ish length of a lon/lat polyline, km. */
export function pathKm(path) {
  let km = 0;
  for (let i = 0; i < path.length - 1; i++) {
    const dx = (path[i + 1][0] - path[i][0]) * KM_PER_DEG_LAT * COS_LAT;
    const dy = (path[i + 1][1] - path[i][1]) * KM_PER_DEG_LAT;
    km += Math.hypot(dx, dy);
  }
  return km;
}

/** Spherical-excess-free planar area of a lon/lat ring, km² (good enough at this scale). */
export function ringKm2(ring) {
  let a = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[(i + 1) % ring.length];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a / 2) * KM_PER_DEG_LAT * KM_PER_DEG_LAT * COS_LAT;
}

/** Ray-casting point-in-ring test in lon/lat space. */
export function pointInRing([lon, lat], ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const hit = yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (hit) inside = !inside;
  }
  return inside;
}
