/**
 * Package the Vincennes logs 4DWM reconstruction as a Webxdc bundle.
 *
 * A .xdc is a deflated ZIP rooted at index.html + manifest.toml. This one is
 * built multi-file with native ES modules (the shape los-alamos.xdc already
 * uses in this repo) rather than inlined into one document, because the point
 * of this app is provenance: the modules, the source data, the generated DjVu
 * plates and both write-ups all travel inside the bundle and stay readable.
 *
 * Three things the packer adds that the web page does not need:
 *
 *   1. `js/vincennes-xdc-data.js` \u2014 the plate manifest and the four DjVu
 *      fixtures embedded as base64. `fetch()` of a bundled file is not
 *      guaranteed across every webxdc host, and the plates are ~4 KB, so the
 *      viewer prefers the embed and falls back to fetch.
 *   2. `webxdc.js` \u2014 the simulator shim, so the bundle also runs from a plain
 *      static server. A messenger overrides this file at runtime.
 *   3. `command-viewer.html` \u2014 the original Nimitz Graybook canvas plot this
 *      reconstruction grew out of, carried along as a second page so the
 *      bundle contains the thing it replaced as well as the replacement.
 *
 *   node scripts/build-vincennes-xdc.mjs
 */

import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
// Prefer the installed package; fall back to the vendored copy so the build
// works in a bare checkout with no node_modules.
const { zipSync } = await import("fflate").catch(() => import("../vendor/fflate/index.mjs"));

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "vincennes-4dwm.xdc";
const mtime = new Date("2026-09-29T00:00:00.000Z"); // reproducible builds

const manifest = `name = "Vincennes Logs \u00b7 4DWM"
source_code_url = "https://github.com/shdwelf/Html5"
`;

/* ---------------------------------------------------------------- staging */

const files = new Map(); // zip path -> Uint8Array
const enc = new TextEncoder();
const put = (rel, data) => files.set(rel, typeof data === "string" ? enc.encode(data) : new Uint8Array(data));
const copy = async (from, to = from) => put(to, await readFile(path.join(root, from)));

/* 1 \u00b7 index.html, with the bundle-only scripts injected -------------------- */

let html = await readFile(path.join(root, "vincennes-4dwm.html"), "utf8");
const moduleTag = '<script type="module" src="./js/vincennes-4dwm.js"></script>';
if (!html.includes(moduleTag)) throw new Error("vincennes-4dwm.html: entry script tag not found");
html = html.replace(
  moduleTag,
  [
    '<script src="./webxdc.js"></script>',
    '  <script src="./js/vincennes-xdc-data.js"></script>',
    `  ${moduleTag}`,
  ].join("\n")
);
put("index.html", html);

/* 2 \u00b7 the source modules, styles and vendor ---------------------------------- */

for (const f of [
  "js/vincennes-4dwm.js",
  "js/vincennes-logmath.js",
  "js/vincennes-logs-data.js",
  "js/vincennes-dem.js",
  "js/vincennes-djvu.js",
  "js/project-y-4dwm.js",
  "css/vincennes-4dwm.css",
  "css/project-y-4dwm.css",
  "vendor/three.module.min.js",
  "vendor/OrbitControls.js",
  "vendor/THREE_LICENSE",
]) {
  await copy(f);
}

/* 3 \u00b7 the data, both embedded and as files ------------------------------------ */

const platesJson = JSON.parse(await readFile(path.join(root, "data/vincennes/plates.json"), "utf8"));
const plateBytes = {};
for (const p of platesJson.plates) {
  const abs = path.join(root, "data/vincennes", p.file);
  const bytes = await readFile(abs);
  if (bytes.length !== p.bytes) {
    throw new Error(`${p.file}: manifest says ${p.bytes} bytes, file is ${bytes.length} \u2014 run tools/make-vincennes-plates.mjs`);
  }
  plateBytes[p.file] = bytes.toString("base64");
  await copy(path.join("data/vincennes", p.file).split(path.sep).join("/"));
}
await copy("data/vincennes/plates.json");
await copy("data/vincennes/dem.json");
await copy("data/vincennes/README.md");

put(
  "js/vincennes-xdc-data.js",
  `/* Generated by scripts/build-vincennes-xdc.mjs \u2014 do not edit.
 *
 * The plate manifest and the four generated DjVu fixtures, embedded so the
 * bundle needs no fetch at all. The same bytes are also present as real files
 * under data/vincennes/djvu/ for anyone unzipping this to inspect them.
 * js/vincennes-djvu.js parses them either way.
 */
globalThis.__VINCENNES_PLATES__ = ${JSON.stringify(platesJson)};
globalThis.__VINCENNES_PLATE_BYTES__ = ${JSON.stringify(plateBytes)};
globalThis.__VINCENNES_XDC__ = { commandViewer: "command-viewer.html", built: "${mtime.toISOString()}" };
`.replace(/<\/script/gi, "<\\/script")
);

/* 4 \u00b7 the viewer this one replaced, and the write-ups ------------------------- */

await copy("apps/vincennes-command-viewer.html", "command-viewer.html");
await copy("docs/vincennes-4dwm-deep-dive.md", "docs/vincennes-4dwm-deep-dive.md");
await copy("docs/source-check-2026-09-29-vincennes.md", "docs/source-check-2026-09-29-vincennes.md");

/* 5 \u00b7 shim, manifest, icon ------------------------------------------------------ */

put(
  "webxdc.js",
  `/* webxdc simulator shim \u2014 a messenger overrides this file at runtime.
 * Present so the bundle also runs from a plain static server, where it is a
 * solo session: updates are accepted and never delivered to anyone. */
window.webxdc = window.webxdc || {
  selfAddr: "local@device",
  selfName: "local",
  sendUpdate() {},
  setUpdateListener: async () => 0,
  getAllUpdates: async () => [],
};
`
);
put("manifest.toml", manifest);

const iconPath = path.join(root, "img/vincennes-icon-256.png");
if (!(await stat(iconPath).catch(() => null))) throw new Error("missing img/vincennes-icon-256.png");
put("icon.png", await readFile(iconPath));

/* ------------------------------------------------------------------ zip */

if (!files.has("index.html") || !files.has("manifest.toml")) {
  throw new Error("bundle missing index.html/manifest.toml");
}

const archive = {};
for (const rel of [...files.keys()].sort()) archive[rel] = [files.get(rel), { level: 9, mtime }];
const bytes = zipSync(archive, { level: 9, mtime });

await writeFile(path.join(root, OUT), bytes);
await mkdir(path.join(root, "dist"), { recursive: true });
await writeFile(path.join(root, "dist", OUT), bytes);

const raw = [...files.values()].reduce((n, b) => n + b.length, 0);
console.log(`Webxdc: ${OUT} (${bytes.length.toLocaleString()} bytes, ${Object.keys(archive).length} entries)`);
console.log(`  raw:    ${raw.toLocaleString()} bytes`);
console.log(`  sha256: ${createHash("sha256").update(bytes).digest("hex")}`);
console.log(`  plates: ${platesJson.plates.length} embedded (${Object.values(plateBytes).reduce((n, b) => n + b.length, 0).toLocaleString()} b64 chars)`);
for (const rel of Object.keys(archive)) {
  console.log(`    ${String(archive[rel][0].length).padStart(8)}  ${rel}`);
}
