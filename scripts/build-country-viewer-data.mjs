#!/usr/bin/env node
// Builds js/country-data.js from the frozen Factbook source register
// (resources/country-viewer/country-factbook-batch1-source-register-2026-10-24.json).
// The register (tools/fetch_factbook_countries.py) is the source of truth; this
// generator only reshapes it. tests/country-viewer.test.mjs deep-checks the two.
import { readFile, writeFile } from "node:fs/promises";

const REGISTER = "resources/country-viewer/country-factbook-batch1-source-register-2026-10-24.json";
const OUT = "js/country-data.js";

const register = JSON.parse(await readFile(REGISTER, "utf8"));
const countries = register.countries.map((c) => ({
  code: c.code,
  name: c.name,
  capital: { name: c.capital.name, lat: c.capital.coords?.[0] ?? null, lon: c.capital.coords?.[1] ?? null },
  lat: c.coords?.[0] ?? null,
  lon: c.coords?.[1] ?? null,
  areaTotalSqKm: c.areaTotalSqKm,
  population: c.population,
  populationText: c.populationText,
  languages: c.languages,
  governmentType: c.governmentType,
  anthemTitle: c.anthem.title,
  anthemLyricsMusic: c.anthem.lyricsMusic,
  location: c.location,
}));

const meta = {
  source: "CIA World Factbook via factbook/factbook.json (CC0 mirror)",
  upstreamCommit: register.upstream.commit,
  register: REGISTER,
  generated: register.generated,
  count: countries.length,
};

const body = `// GENERATED by scripts/build-country-viewer-data.mjs from ${REGISTER}.
// Do not edit by hand; regenerate. Source register pins upstream
// factbook/factbook.json commit ${meta.upstreamCommit} with per-file SHA-256.
export const COUNTRY_DATA_META = ${JSON.stringify(meta, null, 2)};
export const COUNTRIES = ${JSON.stringify(countries, null, 2)};
`;
await writeFile(OUT, body);
console.log(`built ${OUT}: ${countries.length} countries (upstream ${meta.upstreamCommit.slice(0, 12)})`);
