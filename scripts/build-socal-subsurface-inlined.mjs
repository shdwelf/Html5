#!/usr/bin/env node
/**
 * Build the single-file SoCal Subsurface 4Dwm edition and its Webxdc.
 *
 *   node scripts/build-socal-subsurface-inlined.mjs
 *   node scripts/build-socal-subsurface-inlined.mjs --check
 *
 * Outputs:
 *   socal-subsurface-inlined.html
 *   socal-subsurface-inlined.xdc
 *   public/apps/socal-subsurface-inlined/ (the staged archive tree)
 *
 * The canonical multi-file package remains scripts/build-socal-subsurface-xdc.mjs.
 * This builder is the CASEFILES-style counterpart: esbuild resolves the full
 * ES-module graph, the stylesheet and module bundle are placed directly in
 * the document, and the archive contains that inlined document rather than
 * 26 loose source files.
 *
 * The optional USGS DEM is deliberately build-time data. If
 * js/socal-dem-grid.js exists when this runs, esbuild includes it; otherwise
 * a null DEM stub is bundled and the app's documented synthetic relief field
 * is used. Either way the generated file contains no runtime import for it.
 */

import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import esbuild from "esbuild";

const { unzipSync, zipSync } = await import("fflate").catch(
  () => import("../vendor/fflate/index.mjs"),
);

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const mtime = new Date("2026-09-28T00:00:00.000Z");
const standaloneName = "socal-subsurface-inlined.html";
const xdcName = "socal-subsurface-inlined.xdc";
const appDir = path.join(root, "public", "apps", "socal-subsurface-inlined");
const demPath = path.join(root, "js", "socal-dem-grid.js");
const demIncluded = existsSync(demPath);

const manifest = `name = "SoCal Subsurface 4Dwm (Inlined)"
source_code_url = "https://github.com/shdwelf/Html5"
`;

const webxdcShim = `/* webxdc simulator shim - the host overrides this file at runtime. */
window.webxdc = window.webxdc || {
  selfAddr: "local@device",
  selfName: "local",
  sendUpdate() {},
  setUpdateListener: async () => 0,
  getAllUpdates: async () => [],
};
`;

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const readText = (rel) => readFile(path.join(root, rel), "utf8");

/* ---------------------------------------------------------- module bundle */

const optionalDemPlugin = {
  name: "socal-optional-dem",
  setup(build) {
    build.onResolve({ filter: /socal-dem-grid\.js$/ }, (args) => {
      const candidate = path.resolve(args.resolveDir, args.path);
      return existsSync(candidate)
        ? { path: candidate }
        : { path: "socal-dem-grid-absent", namespace: "socal-optional-dem" };
    });
    build.onLoad(
      { filter: /.*/, namespace: "socal-optional-dem" },
      () => ({
        contents: "export const DEM = null;\nexport default null;\n",
        loader: "js",
      }),
    );
  },
};

const bundled = await esbuild.build({
  entryPoints: [path.join(root, "js", "socal-subsurface.js")],
  bundle: true,
  minify: true,
  format: "esm",
  target: "es2022",
  write: false,
  legalComments: "none",
  logLevel: "silent",
  metafile: true,
  plugins: [optionalDemPlugin],
});

let bundleJs = bundled.outputFiles[0].text;
// A literal closing tag in a string or regular expression would terminate
// the host <script> element. This is the standard inline-script escape.
bundleJs = bundleJs.replace(/<\/script/g, "<\\/script");

const bundledInputs = Object.keys(bundled.metafile.inputs)
  .filter((name) => !name.startsWith("socal-optional-dem:"))
  .sort();
for (const required of [
  "js/gpx-geocache.js",
  "js/socal-gazetteer-data.js",
  "js/socal-subsurface-data.js",
  "js/socal-subsurface.js",
  "vendor/OrbitControls.js",
  "vendor/fflate/browser.mjs",
  "vendor/three.module.min.js",
]) {
  if (!bundledInputs.includes(required)) {
    throw new Error(`esbuild graph omitted ${required}`);
  }
}
if (/\bfrom\s+["'][^"']+["']|\bimport\s*\(\s*["'][^"']+["']\s*\)/.test(bundleJs)) {
  throw new Error("inlined SoCal bundle still contains an external module import");
}

/* ------------------------------------------------------------- document */

const [html, css, threeLicense, fflateLicense, icon] = await Promise.all([
  readText("socal-subsurface.html"),
  readText("css/socal-subsurface.css"),
  readText("vendor/THREE_LICENSE"),
  readText("vendor/fflate/LICENSE"),
  readFile(path.join(root, "icon.png")),
]);

if (/<\/style/i.test(css)) throw new Error("SoCal CSS contains a closing style tag");

const licenseComment = `<!--
  Generated by scripts/build-socal-subsurface-inlined.mjs from
  socal-subsurface.html, css/socal-subsurface.css, js/socal-subsurface.js
  and their local module graph. Do not hand-edit this file.

  Optional DEM at build time: ${demIncluded ? "js/socal-dem-grid.js included" : "absent; synthetic relief field"}.
  Bundled modules: ${bundledInputs.join(", ")}.

  Third-party notices
  ===================
  Three.js (vendor/THREE_LICENSE):
${threeLicense.trim().replace(/^/gm, "  ")}

  fflate (vendor/fflate/LICENSE):
${fflateLicense.trim().replace(/^/gm, "  ")}
-->`;

const cssTag = '<link rel="stylesheet" href="./css/socal-subsurface.css" />';
const scriptTag = '<script type="module" src="./js/socal-subsurface.js"></script>';
if (!html.includes(cssTag)) throw new Error(`expected stylesheet tag not found: ${cssTag}`);
if (!html.includes(scriptTag)) throw new Error(`expected module tag not found: ${scriptTag}`);

const shimScript = `<script>\n${webxdcShim}</script>`;
let standalone = html
  .replace("<!DOCTYPE html>", `<!DOCTYPE html>\n${licenseComment}`)
  .replace(cssTag, () => `<style>\n${css}\n</style>`)
  .replace(
    scriptTag,
    () => `${shimScript}\n  <script type="module">\n${bundleJs}\n</script>`,
  );

// The standalone file may still contain ordinary navigational/source links,
// but it must not need another local CSS or JavaScript asset to boot.
for (const forbidden of [
  '<link rel="stylesheet"',
  '<script type="module" src=',
  '<script src=',
  'href="./css/',
  'src="./js/',
  'src="../vendor/',
]) {
  if (standalone.includes(forbidden)) {
    throw new Error(`inlined document still references external asset: ${forbidden}`);
  }
}
for (const required of [
  "SOCAL SUBSURFACE 4Dwm",
  "LOCAL GPX → GEOCACHE REGISTER",
  "window.webxdc = window.webxdc ||",
]) {
  if (!standalone.includes(required)) throw new Error(`inlined document lost ${required}`);
}

// In a Webxdc, webxdc.js is the one host-owned external file: Delta Chat
// replaces the shipped simulator with the real bridge at runtime.
const xdcIndex = standalone.replace(
  shimScript,
  '<script src="./webxdc.js"></script>',
);
if (xdcIndex === standalone || !xdcIndex.includes('<script src="./webxdc.js"></script>')) {
  throw new Error("could not splice webxdc.js into the archive index");
}

/* --------------------------------------------------------------- archive */

const archive = {
  "icon.png": [new Uint8Array(icon), { level: 9, mtime }],
  "index.html": [new TextEncoder().encode(xdcIndex), { level: 9, mtime }],
  "manifest.toml": [new TextEncoder().encode(manifest), { level: 9, mtime }],
  "vendor/THREE_LICENSE": [new TextEncoder().encode(threeLicense), { level: 9, mtime }],
  "vendor/fflate/LICENSE": [new TextEncoder().encode(fflateLicense), { level: 9, mtime }],
  "webxdc.js": [new TextEncoder().encode(webxdcShim), { level: 9, mtime }],
};
const xdcBytes = zipSync(archive, { level: 9, mtime });

// Prove the archive boundary rather than trusting the in-memory object.
const roundTrip = unzipSync(xdcBytes);
const roundTripNames = Object.keys(roundTrip).sort();
const expectedNames = Object.keys(archive).sort();
if (JSON.stringify(roundTripNames) !== JSON.stringify(expectedNames)) {
  throw new Error(`inlined XDC entries changed during zip round-trip: ${roundTripNames.join(", ")}`);
}
const roundTripIndex = new TextDecoder().decode(roundTrip["index.html"]);
if (roundTripIndex !== xdcIndex) throw new Error("inlined XDC index changed during zip round-trip");
for (const forbidden of ['href="./css/', 'src="./js/', 'src="../vendor/']) {
  if (roundTripIndex.includes(forbidden)) {
    throw new Error(`inlined XDC index references an unpackaged asset: ${forbidden}`);
  }
}

/* ---------------------------------------------------------- write/check */

const targets = [
  { rel: standaloneName, bytes: Buffer.from(standalone, "utf8") },
  { rel: xdcName, bytes: Buffer.from(xdcBytes) },
  { rel: "public/apps/socal-subsurface-inlined/index.html", bytes: Buffer.from(xdcIndex, "utf8") },
  { rel: "public/apps/socal-subsurface-inlined/manifest.toml", bytes: Buffer.from(manifest, "utf8") },
  { rel: "public/apps/socal-subsurface-inlined/icon.png", bytes: icon },
  { rel: "public/apps/socal-subsurface-inlined/webxdc.js", bytes: Buffer.from(webxdcShim, "utf8") },
  { rel: "public/apps/socal-subsurface-inlined/vendor/THREE_LICENSE", bytes: Buffer.from(threeLicense, "utf8") },
  { rel: "public/apps/socal-subsurface-inlined/vendor/fflate/LICENSE", bytes: Buffer.from(fflateLicense, "utf8") },
];

let drift = 0;
for (const target of targets) {
  const abs = path.join(root, target.rel);
  const onDisk = await readFile(abs).catch(() => null);
  const current = onDisk && sha256(onDisk) === sha256(target.bytes);
  if (checkOnly) {
    console.log(`${current ? "up to date" : "STALE"} ${target.rel}`);
    if (!current) drift += 1;
  } else if (!current) {
    await mkdir(path.dirname(abs), { recursive: true });
    await writeFile(abs, target.bytes);
    console.log(`wrote ${target.rel} (${target.bytes.length.toLocaleString()} bytes)`);
  } else {
    console.log(`up to date ${target.rel}`);
  }
}

if (!checkOnly) {
  // The staged tree is a deliverable in this repository. Remove anything a
  // previous inlined build left behind so it cannot look packaged when it is
  // not an archive entry. The canonical public/apps/socal-subsurface tree is
  // a different directory and is not touched.
  const expected = new Set(targets
    .map(({ rel }) => rel)
    .filter((rel) => rel.startsWith("public/apps/socal-subsurface-inlined/"))
    .map((rel) => path.join(root, rel)));
  async function prune(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) await prune(abs);
      else if (!expected.has(abs)) await rm(abs, { force: true });
    }
  }
  if (existsSync(appDir)) await prune(appDir);

  await mkdir(path.join(root, "dist"), { recursive: true });
  await writeFile(path.join(root, "dist", xdcName), xdcBytes);
}

console.log(`Standalone: ${standaloneName} (${Buffer.byteLength(standalone).toLocaleString()} bytes)`);
console.log(`Webxdc: ${xdcName} (${xdcBytes.length.toLocaleString()} bytes, ${expectedNames.length} entries)`);
console.log(`  sha256: ${sha256(xdcBytes)}`);
console.log(`  modules: ${bundledInputs.length}; optional DEM: ${demIncluded ? "included" : "absent (synthetic relief)"}`);

if (checkOnly && drift) {
  console.error(`\n${drift} inlined SoCal target(s) out of date — run: node scripts/build-socal-subsurface-inlined.mjs`);
  process.exit(1);
}
