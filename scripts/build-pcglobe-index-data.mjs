#!/usr/bin/env node
// Builds js/pcglobe-index-data.js from the decoded PC Globe register
// (research/pcglobe-java/countries.json, produced by
// tools/pcglobe/PcGlobeReader.java from the 1990 PC Globe files in
// .xfer/pcglobe/). INDEX ONLY: the register contains decoded name and
// label strings; the binary map payload (coordinates, name->record
// pointers) is undecoded, so this data module carries no coordinates
// and nothing built from it may be plotted. The planet viewer shows it
// as an index plate next to the globe plate (which uses Factbook
// capitals for markers instead).
import { readFile, writeFile } from "node:fs/promises";

const SRC = "research/pcglobe-java/countries.json";
const OUT = "js/pcglobe-index-data.js";

const reg = JSON.parse(await readFile(SRC, "utf8"));

const countryNames = reg.namesDat?.countryNames ?? [];
if (countryNames.length !== 216) throw new Error(`NAMES.DAT country run: expected 216 names, got ${countryNames.length}`);
if (!Array.isArray(reg.countries) || reg.countries.length !== 177) {
  throw new Error(`COUNTRY records: expected 177, got ${reg.countries?.length}`);
}
for (const c of reg.countries) {
  for (const k of Object.keys(c)) {
    if (/lat|lon|coord/i.test(k)) throw new Error(`record ${c.file}#${c.index}: coordinate-like field ${k} must never enter the index`);
  }
}

const records = reg.countries.map((c) => ({
  file: c.file,
  index: c.index,
  offset: c.offset,
  length: c.length,
  undecodedPayloadBytes: c.undecodedPayloadBytes,
  features: c.features,
}));
const featureCount = records.reduce((n, r) => n + r.features.length, 0);
const runs = Object.fromEntries((reg.namesDat.stringRuns || []).map((r) => [r.offset, r]));

const meta = {
  source: "PC Globe (1990) decoded registers: NAMES.DAT country-name run and COUNTRY1.DAT / COUNTRY2.DAT label strings",
  decodedBy: reg.generator,
  files: Object.fromEntries(Object.entries(reg.sources || {}).map(([k, v]) => [k, { bytes: v.bytes, sha256: v.sha256 }])),
  countryNameCount: countryNames.length,
  countryRecordCount: records.length,
  featureCount,
  cityNameRun: { count: runs[27379]?.count ?? null, first: runs[27379]?.first ?? null, last: runs[27379]?.last ?? null },
  currencyRun: { count: runs[40036]?.count ?? null, first: runs[40036]?.first ?? null, last: runs[40036]?.last ?? null },
  disclosure:
    "Index only. PC Globe's binary map payload (feature coordinates and the name-to-record pointer table) is undecoded; " +
    "country records are therefore listed by file position, not matched to country names, and nothing from PC Globe is plotted.",
};

const body = `// GENERATED by scripts/build-pcglobe-index-data.mjs from ${SRC}.
// Do not edit by hand; regenerate. Index-only data: no coordinates exist
// in this module (the PC Globe map payload is undecoded), so it must
// never feed a map. See PCGLOBE_INDEX_META.disclosure.
export const PCGLOBE_INDEX_META = ${JSON.stringify(meta, null, 2)};
export const PCGLOBE_COUNTRY_NAMES = ${JSON.stringify(countryNames, null, 2)};
export const PCGLOBE_COUNTRY_RECORDS = ${JSON.stringify(records, null, 2)};
`;
await writeFile(OUT, body);
console.log(`built ${OUT}: ${countryNames.length} country names, ${records.length} country records, ${featureCount} feature labels (index-only, no coordinates)`);
