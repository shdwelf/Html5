#!/usr/bin/env node
/**
 * Build the browser data modules for the S6 historical-network viewer.
 *
 *   node scripts/build-historical-network.mjs          # write JS modules
 *   node scripts/build-historical-network.mjs --check  # fail if stale
 *
 * Sources of truth (schemaVersion 1 evidence packs):
 *   resources/historical-network/keyhole-evidence-pack-2026-10-22.json
 *   resources/historical-network/comms-history-seed-2026-10-23.json
 *   resources/historical-network/cicada-3301-poster-seed-2026-10-23.json
 * Outputs:
 *   js/historical-network-keyhole-data.js  (KEYHOLE_EVIDENCE_PACK)
 *   js/historical-network-comms-data.js    (COMMS_HISTORY_PACK)
 *   js/historical-network-cicada-data.js   (CICADA_3301_PACK)
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const MODULES = [
  {
    source: "keyhole-evidence-pack-2026-10-22.json",
    output: "historical-network-keyhole-data.js",
    exportName: "KEYHOLE_EVIDENCE_PACK",
    title: "Keyhole BBS evidence-pack data module",
    note: "This is a Phase 0 citation fixture, not a captured bulk BBS-list dataset.",
  },
  {
    source: "comms-history-seed-2026-10-23.json",
    output: "historical-network-comms-data.js",
    exportName: "COMMS_HISTORY_PACK",
    title: "Communications-history seed data module (ARPANET / FidoNet / Mojave payphone)",
    note: "Cited public facts only; no nodelist or BBS-list bulk data is bundled (local-import-only rights decision).",
  },
  {
    source: "cicada-3301-poster-seed-2026-10-23.json",
    output: "historical-network-cicada-data.js",
    exportName: "CICADA_3301_PACK",
    title: "Cicada 3301 (2012) US QR-poster seed data module",
    note: "Historical 2012 poster sites; the posters are long gone and no puzzle content is included.",
  },
];

const check = process.argv.includes("--check");
let stale = false;

for (const mod of MODULES) {
  const sourcePath = path.join(root, "resources", "historical-network", mod.source);
  const outputPath = path.join(root, "js", mod.output);
  const source = JSON.parse(await readFile(sourcePath, "utf8"));

  if (source.schemaVersion !== 1) {
    throw new Error(`unsupported historical-network schemaVersion in ${mod.source}: ${source.schemaVersion}`);
  }
  if (!Array.isArray(source.snapshots) || !Array.isArray(source.observations)) {
    throw new Error(`historical-network evidence pack ${mod.source} must contain snapshots and observations arrays`);
  }

  const output = `/**
 * HISTORICAL NETWORK — ${mod.title}.
 *
 * Generated by scripts/build-historical-network.mjs from
 * resources/historical-network/${mod.source}.
 * Do not edit by hand. ${mod.note}
 */

export const ${mod.exportName} = ${JSON.stringify(source, null, 2)};
`;

  if (check) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== output) {
      console.error(`${mod.output} is stale; run node scripts/build-historical-network.mjs`);
      stale = true;
    } else {
      console.log(`${mod.output} is current`);
    }
  } else {
    await writeFile(outputPath, output);
    console.log(`built ${path.relative(root, outputPath)} from ${path.relative(root, sourcePath)}`);
  }
}

if (check && stale) process.exit(1);
if (check) console.log("historical-network data modules are current");
