#!/usr/bin/env node
/**
 * Build the browser data module for the S6 historical-network Keyhole slice.
 *
 *   node scripts/build-historical-network.mjs          # write JS module
 *   node scripts/build-historical-network.mjs --check  # fail if stale
 *
 * Source of truth:
 *   resources/historical-network/keyhole-evidence-pack-2026-10-22.json
 * Output:
 *   js/historical-network-keyhole-data.js
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "resources", "historical-network", "keyhole-evidence-pack-2026-10-22.json");
const outputPath = path.join(root, "js", "historical-network-keyhole-data.js");
const source = JSON.parse(await readFile(sourcePath, "utf8"));

if (source.schemaVersion !== 1) {
  throw new Error(`unsupported historical-network schemaVersion: ${source.schemaVersion}`);
}
if (!Array.isArray(source.snapshots) || !Array.isArray(source.observations)) {
  throw new Error("historical-network evidence pack must contain snapshots and observations arrays");
}

const output = `/**
 * HISTORICAL NETWORK — Keyhole BBS evidence-pack data module.
 *
 * Generated by scripts/build-historical-network.mjs from
 * resources/historical-network/keyhole-evidence-pack-2026-10-22.json.
 * Do not edit by hand. This is a Phase 0 citation fixture, not a captured
 * bulk BBS-list dataset.
 */

export const KEYHOLE_EVIDENCE_PACK = ${JSON.stringify(source, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error("historical-network-keyhole-data.js is stale; run node scripts/build-historical-network.mjs");
    process.exit(1);
  }
  console.log("historical-network Keyhole data module is current");
} else {
  await writeFile(outputPath, output);
  console.log(`built ${path.relative(root, outputPath)} from ${path.relative(root, sourcePath)}`);
}
