const dens = (path, n) => { // linear interp along polyline -> n multipoints
  const segs = []; let total = 0;
  for (let i = 0; i < path.length - 1; i++) { const L = Math.hypot(path[i+1][0]-path[i][0], path[i+1][1]-path[i][1]); segs.push(L); total += L; }
  const pts = []; let dTarget = 0;
  for (let k = 0; k < n; k++) {
    dTarget = (k / (n - 1)) * total; let d = 0;
    for (let i = 0; i < segs.length; i++) {
      if (dTarget <= d + segs[i]) { const t = (dTarget - d) / segs[i]; pts.push([path[i][0] + (path[i+1][0]-path[i][0])*t, path[i][1] + (path[i+1][1]-path[i][1])*t].map(v => Math.round(v*1e6)/1e6)); break; }
      d += segs[i];
    }
  }
  return pts;
};

