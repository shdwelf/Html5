/**
 * INGRESS INTEL 4Dwm — the offline register (SIM).
 *
 * When no rung of the ladder answers — which, from a plain static origin, is the
 * normal case — the viewer still needs something to draw, or it is a globe with
 * nothing on it. This generator supplies that: a *synthetic* faction network laid
 * over *real* coordinates taken from the repo's USGS GNIS register.
 *
 * The split is deliberate and is the whole point of this file:
 *   · positions and place names — real, from js/socal-gazetteer-data.js, which is
 *     itself derived from the USGS Geographic Names Information System (17 USC 105)
 *   · everything else — team, level, health, resonators, links, fields, comms —
 *     generated by a seeded PRNG, deterministic per (seed, bbox), and marked on
 *     every record with a provenance string that says so
 *
 * It is deterministic on purpose: two agents loading the same tile range see the
 * same fake network, so the theater can be demoed and screenshotted without the
 * picture changing underneath, and the test suite can pin it. It is *not* a
 * model of the game: no claim is made that these places are portals, or that any
 * faction holds anything.
 *
 * Determinism chain: hash(seed + bbox) → mulberry32 → uniform draws. No
 * Math.random, no Date.now() in the geometry — the timeline is anchored on a
 * fixed nominal epoch so ages are stable, and the *displayed* age is computed
 * from the anchor, not baked into it.
 */

import { GAZ_ROWS } from "./socal-gazetteer-data.js";
import { makeGazetteerIndex, searchBox } from "./socal-gazetteer.js";
import { emptyFrame, greatCircleKm, scoreFrame } from "./ingress-intel-proto.js";
import { RULES } from "./ingress-intel-data.js";

export const SIM_NOTICE =
  "SIM — synthetic network over real USGS gazetteer coordinates. No Niantic data, no game state, nothing here is a claim about who holds anything.";

/** Nominal epoch the fake comms timeline is anchored on (fixed, for determinism). */
const EPOCH_MS = Date.UTC(2026, 9, 7, 6, 0, 0);

const KIND_WEIGHT = {
  "Populated Place": 0.95,
  Park: 0.8,
  "Historic Place": 0.75,
  Locale: 0.7,
  Mine: 0.6,
  Oilfield: 0.6,
  "Post Office": 0.55,
  School: 0.5,
  Stadium: 0.72,
  "Tourist Attraction": 0.78,
  Airport: 0.66,
  Canal: 0.5,
  Dam: 0.5,
  Reservoir: 0.45,
  Lake: 0.4,
  Summit: 0.35,
  "Civil": 0.6,
};

/* ------------------------------------------------------------------ rng */

function hashSeed(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* ------------------------------------------------------------ front model */

/**
 * A wavy contact line: longitude as a function of latitude, plus two harmonics
 * whose phases come from the seed. West of it reads Resistance, east of it
 * Enlightened, and a band ±0.2° around it is the contested zone where the
 * faction is a coin flip — which is exactly the shape of a real front and why
 * the picture looks credible, while being nothing but a sine wave.
 */
function makeFront(rng, bbox) {
  const phase1 = rng() * Math.PI * 2;
  const phase2 = rng() * Math.PI * 2;
  const amp1 = 0.25 + rng() * 0.5;
  const amp2 = 0.1 + rng() * 0.2;
  const tilt = (rng() - 0.5) * 0.7;
  const latMid = (bbox.lat0 + bbox.lat1) / 2;
  const latHalf = Math.max(1e-6, (bbox.lat1 - bbox.lat0) / 2);
  /**
   * Longitude of the contact line at `lat`, for a frame spanning lon0..lon1.
   * The wave is driven by `u`, latitude normalised to this frame, so the front
   * keeps the same shape whether it is drawn over the basin or the planet.
   */
  return function frontLon(lat, lon0, lon1) {
    const mid = (lon0 + lon1) / 2;
    const span = (lon1 - lon0) * 0.32;
    const u = (lat - latMid) / latHalf;
    return (
      mid +
      span * (tilt * u * 0.5 + Math.sin(u * 1.7 + phase1) * 0.6 * amp1 + Math.sin(u * 3.1 + phase2) * 0.4 * amp2)
    );
  };
}

/* ------------------------------------------------------- the sim generator */

/**
 * buildSimFrame({ bbox, seed, limit, index }) → frame
 * The frame carries `sim: true` and per-record provenance; nothing else in the
 * app should special-case it, which is the point of generating it in the same
 * shape the wire decoder emits.
 */
export function buildSimFrame({ bbox, seed = "socal-gaz", limit = 90, index = null } = {}) {
  const frame = emptyFrame("sim");
  frame.sim = true;
  if (!bbox) { frame.warnings.push("sim needs a bbox"); return frame; }

  const idx = index || makeGazetteerIndex(GAZ_ROWS);
  const rows = searchBox(idx, bbox, { limit: 4000 });
  if (!rows.length) {
    frame.warnings.push("no gazetteer rows in this bbox — the register does not cover it, so the sim has nothing to hang on");
    return frame;
  }
  const rng = mulberry32(hashSeed(`${seed}|${bbox.lon0.toFixed(3)},${bbox.lat0.toFixed(3)},${bbox.lon1.toFixed(3)},${bbox.lat1.toFixed(3)}|${limit}`));
  const frontLon = makeFront(rng, bbox);
  const linkMaxKm = RULES.find((r) => r.key === "linkMaxKm").value;

  // Sample the register with class-weighted acceptance, spread over the frame.
  const picked = [];
  for (const r of rows) {
    const w = KIND_WEIGHT[r.fclass] ?? 0.3;
    const keep = rng() < 0.22 + w * 0.55;
    if (keep) picked.push({ r, w });
  }
  picked.sort((a, b) => b.w - a.w);
  const chosen = picked.slice(0, limit);

  const portals = [];
  for (const { r, w } of chosen) {
    const fLon = frontLon(r.lat, bbox.lon0, bbox.lon1);
    const delta = r.lon - fLon; // negative = west of the front
    const contested = Math.abs(delta) < 0.2;
    let team;
    if (contested) team = rng() < 0.5 ? "RES" : "ENL";
    else team = delta < 0 ? (rng() < 0.88 ? "RES" : "ENL") : (rng() < 0.88 ? "ENL" : "RES");
    // Sparse desert gets unclaimed portals — a real network is mostly neutral
    // ground where nobody has bothered to plant anything.
    if (rng() > 0.35 + w * 0.55) team = "NEU";

    const level = team === "NEU" ? 0 : Math.max(1, Math.min(8, Math.round(1 + w * 6 + rng() * 2.4)));
    const health = team === "NEU" ? 0 : Math.max(6, Math.min(100, Math.round(35 + rng() * 65)));
    const resCount = team === "NEU" ? 0 : Math.max(1, Math.round((level * 8 * health) / 100 / 8) || 1);
    const resonators = [];
    for (let s = 0; s < 8; s++) {
      if (s >= resCount) break;
      const lv = Math.max(1, Math.min(level, level - Math.floor(rng() * 3)));
      resonators.push({
        slot: s,
        level: lv,
        energy: Math.round(lv * 1000 * (0.25 + rng() * 0.75) * (health / 100)),
        owner: `SIM${(hashSeed(`${r.name}|${s}`) % 9973).toString(36).toUpperCase()}`,
        agent: true,
      });
    }
    const mu = resonators.reduce((s, x) => s + x.level, 0);
    portals.push({
      seq: portals.length + 1,
      kind: "portal",
      guid: `sim.${(hashSeed(r.name) >>> 0).toString(16)}.9`,
      title: r.name,
      lat: r.lat,
      lon: r.lon,
      team,
      color: team === "RES" ? "#0088ff" : team === "ENL" ? "#03dc03" : "#ff6600",
      levelColor: team === "NEU" ? "#3a4757" : undefined,
      level: team === "NEU" ? 0 : level,
      health: team === "NEU" ? null : health,
      resCount: team === "NEU" ? 0 : resCount,
      resonators,
      mods: [],
      image: "",
      timestamp: EPOCH_MS - Math.floor(rng() * 86400000 * 9),
      mu,
      gnis: r.gnis || null,
      gnisClass: r.fclass,
      county: r.county,
      verified: r.verified,
      sim: true,
      tier: "context",
      provenance: `sim · position USGS GNIS “${r.name}” (${r.county} County, ${r.fclass}) · state generated by mulberry32("${seed}")`,
    });
  }

  // Nearest-neighbour links within the published range, same team only.
  const links = [];
  const seenLink = new Set();
  for (const a of portals) {
    if (a.team === "NEU") continue;
    const near = portals
      .filter((b) => b !== a && b.team === a.team)
      .map((b) => ({ b, d: greatCircleKm(a.lat, a.lon, b.lat, b.lon) }))
      .filter((x) => x.d > 0.5 && x.d <= linkMaxKm)
      .sort((x, y) => x.d - y.d)
      .slice(0, 2 + (rng() < 0.4 ? 1 : 0));
    for (const { b } of near) {
      const key = [a.guid, b.guid].sort().join("|");
      if (seenLink.has(key)) continue;
      seenLink.add(key);
      links.push({
        seq: links.length + 1,
        kind: "link",
        guid: `sim.${(hashSeed(key) >>> 0).toString(16)}.b`,
        team: a.team,
        color: a.color,
        oGuid: a.guid,
        dGuid: b.guid,
        from: { lat: a.lat, lon: a.lon },
        to: { lat: b.lat, lon: b.lon },
        lengthKm: greatCircleKm(a.lat, a.lon, b.lat, b.lon),
        timestamp: EPOCH_MS - Math.floor(rng() * 86400000 * 4),
        sim: true,
        tier: "context",
        provenance: `sim · nearest-neighbour pair within the ${linkMaxKm} km published limit`,
      });
    }
  }

  // Fields only where all three edges exist — the rule, applied to the fake
  // links, so the triangles that are drawn are triangles that were actually
  // linked rather than eyeballed.
  const linkSet = new Set(links.map((l) => [l.oGuid, l.dGuid].sort().join("|")));
  const byTeamGuides = new Map();
  for (const l of links) {
    if (!byTeamGuides.has(l.team)) byTeamGuides.set(l.team, new Map());
    const m = byTeamGuides.get(l.team);
    const list = m.get(l.oGuid) || [];
    list.push(l.dGuid);
    m.set(l.oGuid, list);
  }
  const fields = [];
  const seenField = new Set();
  for (const [team, adj] of byTeamGuides) {
    for (const [a, bs] of adj) {
      for (const b of bs) {
        for (const c of adj.get(b) || []) {
          if (c === a || c === b) continue;
          if (!linkSet.has([a, c].sort().join("|"))) continue;
          const key = [a, b, c].sort().join("|");
          if (seenField.has(key)) continue;
          seenField.add(key);
          const pts = [a, b, c].map((g) => portals.find((p) => p.guid === g)).filter(Boolean);
          if (pts.length < 3) continue;
          const mu = Math.min(...pts.map((p) => p.mu || 0));
          fields.push({
            seq: fields.length + 1,
            kind: "field",
            guid: `sim.${(hashSeed(key) >>> 0).toString(16)}.c`,
            team,
            color: team === "RES" ? "#0088ff" : "#03dc03",
            corners: pts.map((p) => ({ lat: p.lat, lon: p.lon, guid: p.guid })),
            mu,
            timestamp: EPOCH_MS - Math.floor(rng() * 86400000 * 3),
            sim: true,
            tier: "context",
            provenance: "sim · triangle closed by three generated links",
          });
        }
      }
    }
  }

  // A 24 h comms strip, so the timeline panel has a shape to show.
  const ACTION = [
    ["DEPLOY_RES", "deployed a resonator on"],
    ["STRIKE_RES", "struck a resonator of"],
    ["CAPTURE", "captured"],
    ["LINK", "linked to"],
    ["FIELD", "created a control field from"],
    ["MINDSHIELD", "raised a mind shield on"],
    ["RAID", "raided"],
    ["MOD", "installed a mod on"],
  ];
  const plexts = [];
  for (let i = 0; i < Math.min(160, portals.length * 2); i++) {
    const p = portals[Math.floor(rng() * portals.length)];
    const [type, verb] = ACTION[Math.floor(rng() * ACTION.length)];
    const minsAgo = Math.floor(rng() * 1440);
    plexts.push({
      seq: i + 1,
      kind: "plext",
      time: EPOCH_MS - minsAgo * 60000,
      team: p.team === "NEU" ? "NEU" : p.team,
      color: p.color,
      lat: p.lat,
      lon: p.lon,
      geo: true,
      agent: `SIM${(hashSeed(`agent${i}`) % 9973).toString(36).toUpperCase()}`,
      text: `${type.toLowerCase().replace(/_/g, " ")} · ${verb} “${p.title}”`,
      minsAgo,
      sim: true,
      tier: "context",
      provenance: "sim · synthetic comms event, timeline anchored on a nominal epoch",
    });
  }
  plexts.sort((x, y) => y.time - x.time);

  frame.portals = portals;
  frame.links = links;
  frame.fields = fields;
  frame.plexts = plexts;
  frame.fetched = EPOCH_MS;
  frame.anchor = EPOCH_MS;
  frame.simNotice = SIM_NOTICE;
  frame.provenance = `sim · ${portals.length} portals from ${rows.length} gazetteer rows in frame · ${links.length} links · ${fields.length} closed triangles · ${plexts.length} comms events`;
  frame.stats = scoreFrame(frame);
  frame.warnings.push(SIM_NOTICE);
  return frame;
}

/** Per-tile deterministic view: same bbox, same network — no flicker on pan. */
export function simSeedForBBox(bbox, seed = "socal-gaz") {
  return hashSeed(`${seed}|${bbox.lon0.toFixed(3)},${bbox.lat0.toFixed(3)},${bbox.lon1.toFixed(3)},${bbox.lat1.toFixed(3)}`);
}

/** Global sim for the globe view: coarse, continental, obviously illustrative. */
export function buildGlobalSimFrame({ seed = "planet", limit = 260 } = {}) {
  const bbox = { lon0: -179, lon1: 179, lat0: -56, lat1: 78 };
  const idx = makeGazetteerIndex(GAZ_ROWS);
  // The register is SoCal-only, so the globe gets the same generator pointed at
  // the whole frame; where there are no rows the globe falls back to a sparse
  // graticule-anchored set rather than inventing place names.
  const rows = searchBox(idx, bbox, { limit: 4000 });
  if (!rows.length) {
    const frame = emptyFrame("sim");
    frame.sim = true;
    frame.warnings.push("the offline register covers SoCal only — the globe shows the graticule and no network until a live frame arrives");
    return frame;
  }
  return buildSimFrame({ bbox, seed, limit, index: idx });
}

