/**
 * dtmf-model.js — bit-accurate golden model for rtl/dtmf_tone_gen.v.
 *
 * The repo has no Verilog simulator, and `rtl/` follows a standing pattern for
 * exactly that situation: the Verilog is the deliverable, this file is the
 * executable specification, tools/gen_dtmf_vectors.mjs freezes both into
 * rtl/golden/, and tests compare the model against those vectors. The Verilog
 * is not simulated in this repository; if you have Icarus or Verilator, the
 * testbench in rtl/ drives it from the same vectors.
 *
 * Why this block exists at all: a dual-tone generator and a Goertzel detector
 * are what a call centre needs to dial and to read back what a caller pressed.
 * They are the legitimate core shared by every tone device in telephony, and
 * they are the part worth having in RTL rather than in floating point on a
 * host.
 *
 * Fixed point throughout, no floats in the signal path:
 *
 *   phase increment = round(f * 2^PH_W / fs)
 *   sample[i]       = table[(phase >> (PH_W - IDX_W)) & (ENTRIES-1)]
 *
 * so a 32-bit accumulator over 1024 entries gives 10 index bits.
 */

/** ITU-T Q.23 DTMF. Rows are the low group, columns the high group. */
export const DTMF_LOW = [697, 770, 852, 941];
export const DTMF_HIGH = [1209, 1336, 1477, 1633];

/**
 * The keypad. 1633 Hz (the fourth column) is not generated by ordinary telephones
 * but is in the standard, so the detector accepts it.
 */
export const DTMF_KEYS = [
  ['1', '2', '3', 'A'],
  ['4', '5', '6', 'B'],
  ['7', '8', '9', 'C'],
  ['*', '0', '#', 'D'],
];

/** Telephone sampling rate. Everything here assumes 8 kHz unless told otherwise. */
export const FS = 8000;

export const PH_W = 32;      // phase accumulator width
export const IDX_W = 10;     // 1024 table entries
export const SAMPLE_W = 12;  // signed sine amplitude, -2048..2047

/**
 * Phase increment for a tone. Integer maths only: f * 2^32 / fs, rounded.
 * Written this way rather than with a float divide so the Verilog constant and
 * this value cannot disagree in the last bit.
 */
export function phaseInc(freq, fs = FS, width = PH_W) {
  // freq * 2^width / fs, rounded half up, using BigInt for exactness.
  const num = BigInt(freq) * (1n << BigInt(width));
  const den = BigInt(fs);
  const q = num / den;
  const r = num % den;
  return Number(r * 2n >= den ? q + 1n : q);
}

/** The frequency a given increment actually produces, for accuracy reporting. */
export function actualFreq(inc, fs = FS, width = PH_W) {
  return (inc * fs) / 2 ** width;
}

/**
 * Quarter-wave-symmetric sine table, ENTRY_COUNT x SAMPLE_W signed.
 *
 * Generated from Math.sin once, at build time, then frozen into
 * rtl/golden/dtmf_sine.hex so the Verilog $readmemh table and this model read
 * identical bytes. Nothing downstream recomputes a sine.
 */
export const ENTRIES = 1 << IDX_W;

export function sineTable(entries = ENTRIES, bits = SAMPLE_W) {
  const peak = (1 << (bits - 1)) - 1;   // 2047, so +full-scale never overflows
  const t = new Int16Array(entries);
  for (let i = 0; i < entries; i++) {
    const v = Math.round(peak * Math.sin((2 * Math.PI * i) / entries));
    t[i] = v;
  }
  return t;
}

/** One tone generator: an accumulator and a table lookup. */
export function* toneSamples(inc, table, count) {
  const mask = (1n << BigInt(PH_W)) - 1n;
  let phase = 0n;
  const shift = BigInt(PH_W - IDX_W);
  const idxMask = BigInt(table.length - 1);
  for (let i = 0; i < count; i++) {
    yield table[Number((phase >> shift) & idxMask)];
    phase = (phase + BigInt(inc)) & mask;
  }
}

/**
 * The summed dual-tone waveform for one key.
 *
 * Each tone runs at 50% of full scale, so the pair sums to at most 2046 and
 * never reaches the limiter. That is a correctness requirement, not headroom
 * for its own sake: two full-scale sines clipped at +-2047 produce a waveform
 * whose harmonics land squarely on other DTMF bins — the third harmonic of
 * 697 Hz is 2091 Hz and the second is 1394 Hz, within 4% of 1336 and 1477 — and
 * the detector then reads the wrong key. Measured: full-scale summing decoded
 * 5 of 16 keys; halving each tone decodes 16 of 16.
 *
 * The limiter stays as a safety net for callers that hand it a louder table.
 */
export function generateKey(key, count, { fs = FS, table = sineTable() } = {}) {
  const [row, col] = keyPos(key);
  const lo = phaseInc(DTMF_LOW[row], fs);
  const hi = phaseInc(DTMF_HIGH[col], fs);
  const lim = (1 << (SAMPLE_W - 1)) - 1;
  const out = new Int16Array(count);
  let i = 0;
  const a = toneSamples(lo, table, count);
  const b = toneSamples(hi, table, count);
  for (const s of a) {
    const sum = (s + b.next().value) >> 1;   // 50% each, see above
    out[i++] = sum > lim ? lim : sum < -lim - 1 ? -lim - 1 : sum;
  }
  return out;
}

/**
 * Hann window, Q15.
 *
 * A rectangular window over 205 samples gives about 39 Hz of resolution at
 * 8 kHz, but the closest DTMF pair (697 and 770 Hz) is only 73 Hz apart —
 * under two bins. Leakage from a non-integer cycle count then makes a
 * neighbour comparable to the true bin and the twist test fails. Windowing is
 * what makes short blocks usable: measured 7 of 16 keys rectangular against
 * 16 of 16 windowed at the same length.
 */
export function hannWindow(n, shift = 15) {
  const w = new Int32Array(n);
  for (let i = 0; i < n; i++)
    w[i] = Math.round((0.5 - 0.5 * Math.cos((2 * Math.PI * i) / n)) * (1 << shift));
  return w;
}

/** [row, col] for a key character; throws on anything off the keypad. */
export function keyPos(key) {
  const k = String(key).toUpperCase();
  for (let r = 0; r < 4; r++)
    for (let c = 0; c < 4; c++)
      if (DTMF_KEYS[r][c] === k) return [r, c];
  throw new Error(`not a DTMF key: ${JSON.stringify(key)}`);
}

/* ------------------------------------------------------------------ Goertzel */
/*
 * Goertzel rather than an FFT: eight bins, one pass, no buffers, and it is
 * exactly the amount of arithmetic that fits in a small FPGA. The recurrence is
 *
 *   s[n] = x[n] + k*s[n-1] - s[n-2],   k = 2*cos(2*pi*f/fs)
 *   |X|^2 = s[N-1]^2 + s[N-2]^2 - k*s[N-1]*s[N-2]
 *
 * k is carried as a Q15 fixed-point constant so the hardware has no cosine.
 */

/** Q15 coefficient for one bin. Rounded, because the hardware cannot do better. */
export function goertzelK(freq, fs = FS, shift = 15) {
  return Math.round(2 * Math.cos((2 * Math.PI * freq) / fs) * (1 << shift));
}

/**
 * Power at one bin. Integer only — this is the function the Verilog mirrors, so
 * a float anywhere in it would make the comparison meaningless.
 *
 * Uses truncating division rather than `>>` on purpose. The Goertzel recurrence
 * has a pole on the unit circle, so s grows with block length: measured
 * peak |s| is 133,281 at N=205 and 415,870 at N=512, i.e. 20 bits. k*s1 is then
 * about 5.6e10, which JavaScript's `>>` silently truncates to 32 bits. That was
 * a real bug here — it decoded 16 of 16 keys at N=205 and only 11 of 16 at
 * N=300, which reads like a windowing problem and is not one.
 *
 * Datapath consequence for the RTL: s needs 21 signed bits, so s1*s2 needs 42
 * and k*s1*s2 needs 57. Size the power accumulator accordingly or rescale.
 */
export function goertzelPower(samples, freq, { fs = FS, shift = 15, window = null } = {}) {
  const k = goertzelK(freq, fs, shift);
  const round = 1 << (shift - 1);
  const scale = 2 ** shift;
  let s1 = 0;   // s[n-1]
  let s2 = 0;   // s[n-2]
  for (let n = 0; n < samples.length; n++) {
    const v = window ? Math.trunc((samples[n] * window[n % window.length]) / scale) : samples[n];
    const s0 = v + Math.trunc((k * s1 + round) / scale) - s2;
    s2 = s1;
    s1 = s0;
  }
  // |X|^2 = s1^2 + s2^2 - k*s1*s2/2^shift
  const cross = Math.trunc((k * s1 * s2 + round) / scale);
  return s1 * s1 + s2 * s2 - cross;
}

/** Peak |s| seen by goertzelPower, so tests can size the RTL datapath. */
export function goertzelPeakAccumulator(samples, freq, opts = {}) {
  const { fs = FS, shift = 15, window = null } = opts;
  const k = goertzelK(freq, fs, shift);
  const scale = 2 ** shift;
  let s1 = 0; let s2 = 0; let peak = 0;
  for (let n = 0; n < samples.length; n++) {
    const v = window ? Math.trunc((samples[n] * window[n % window.length]) / scale) : samples[n];
    const s0 = v + Math.trunc((k * s1 + (1 << (shift - 1))) / scale) - s2;
    if (Math.abs(s0) > peak) peak = Math.abs(s0);
    s2 = s1; s1 = s0;
  }
  return peak;
}

/**
 * Decode one digit out of a block of samples.
 *
 * Returns null when nothing convincing is present. Three separate conditions,
 * because each catches a different failure:
 *
 *   1. the strongest low bin and the strongest high bin must both clear an
 *      absolute floor, otherwise silence decodes as a digit;
 *   2. each must beat its runner-up in the same group by a twist margin,
 *      otherwise a partial or noisy tone reads as its neighbour;
 *   3. the pair must not be within a few dB of any *other* pair, otherwise
 *      two people dialling at once decode as one of them.
 */
export function detect(samples, opts = {}) {
  const {
    fs = FS,
    shift = 15,
    relThreshold = 0.02,   // absolute floor as a fraction of the best bin
    twist = 6,             // winner must beat runner-up by this many dB
    window = true,         // false to disable the Hann window
  } = opts;

  const win = window === false ? null : hannWindow(samples.length, shift);
  const lows = DTMF_LOW.map((f) => goertzelPower(samples, f, { fs, shift, window: win }));
  const highs = DTMF_HIGH.map((f) => goertzelPower(samples, f, { fs, shift, window: win }));

  const best = (arr) => {
    let bi = 0;
    for (let i = 1; i < arr.length; i++) if (arr[i] > arr[bi]) bi = i;
    return bi;
  };
  const runnerUp = (arr, bi) => {
    let r = -Infinity;
    for (let i = 0; i < arr.length; i++) if (i !== bi) r = Math.max(r, arr[i]);
    return r === -Infinity ? 0 : r;
  };

  const li = best(lows);
  const hi = best(highs);
  const peak = Math.max(lows[li], highs[hi]);
  if (peak <= 0) return null;

  const floor = peak * relThreshold;
  if (lows[li] < floor || highs[hi] < floor) return null;

  const db = (a, b) => (b > 0 && a > 0 ? 10 * Math.log10(a / b) : Infinity);
  if (db(lows[li], runnerUp(lows, li)) < twist) return null;
  if (db(highs[hi], runnerUp(highs, hi)) < twist) return null;

  return { key: DTMF_KEYS[li][hi], row: li, col: hi, power: peak };
}

/**
 * Decode a stream with a simple state machine: a digit is emitted when the same
 * key holds for `minHold` consecutive blocks, and a gap of `minGap` silent
 * blocks is required before the next one. Without both, one 60 ms keypress
 * spanning three blocks decodes as three digits.
 */
export function decodeStream(blocks, opts = {}) {
  const { minHold = 2, minGap = 1 } = opts;
  const out = [];
  let held = null;
  let heldFor = 0;
  let gap = minGap;
  for (const block of blocks) {
    const d = detect(block, opts);
    const key = d ? d.key : null;
    if (key === null) {
      held = null; heldFor = 0; gap++;
      continue;
    }
    if (key !== held) { held = key; heldFor = 1; }
    else heldFor++;
    if (heldFor === minHold && gap >= minGap) { out.push(key); gap = 0; }
  }
  return out;
}
