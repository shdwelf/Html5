// Sort by length descending so longer names match first (original semantics).
export const GAZETTEER = RAW
  .map(([name, lon, lat]) => ({ name, lon, lat, key: name.toLowerCase() }))
  .sort((a, b) => b.name.length - a.name.length);

/** Longest-first match of `text` (already lowercased) against the table. */
export function gazetteerMatch(text) {
  for (const g of GAZETTEER) {
    const k = g.key;
    const idx = text.indexOf(k);
    if (idx === -1) continue;
    const before = idx === 0 ? " " : text[idx - 1];
    const after = idx + k.length >= text.length ? " " : text[idx + k.length];
    if (/[a-z0-9]/.test(before) || /[a-z0-9]/.test(after)) continue;
    return g;
  }
  return null;
}
