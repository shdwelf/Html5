export const SANCTUARIES = ALL.filter((n) => n.pad === PAD);

export function money(n) {
  if (!n) return "—";
  if (n >= 1000) return `$${(n / 1000).toFixed(2)}B`;
  if (n >= 1) return `$${n.toFixed(1)}M`;
  return `$${(n * 1000).toFixed(0)}K`;
}

export function sanctuariesInParish(name) {
  return SANCTUARIES.filter((s) => s.parish === name);
}

export function findSanctuary(q) {
  const s = String(q || "").toLowerCase();
  return (
    SANCTUARIES.find(
      (n) =>
        n.id === q ||
        n.short.toLowerCase() === s ||
        n.name.toLowerCase().includes(s) ||
        n.ein === q
    ) || null
  );
}
